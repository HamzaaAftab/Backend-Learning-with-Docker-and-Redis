import mongoose from "mongoose";

// Define the schema
const userSchema = new mongoose.Schema({
    fullName: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    }
});

// Create a model based on the schema
export const User = mongoose.model("User", userSchema);
